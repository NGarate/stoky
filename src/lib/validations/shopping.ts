import { z } from "zod";

export const shoppingListSchema = z.object({
  name: z.string().min(1),
  isAutoGenerated: z.boolean().default(false),
});

export const updateShoppingListSchema = shoppingListSchema.partial().extend({
  id: z.string(),
});

export const shoppingItemSchema = z.object({
  shoppingListId: z.string(),
  productId: z.string().optional(),
  customName: z.string().optional(),
  quantity: z.number().default(1),
  unit: z.string().optional(),
});

export const updateShoppingItemSchema = z.object({
  id: z.string(),
  isChecked: z.boolean().optional(),
  quantity: z.number().optional(),
});

export const shoppingListQuerySchema = z.object({
  includeCompleted: z.boolean().default(false),
});

export type ShoppingListInput = z.infer<typeof shoppingListSchema>;
export type UpdateShoppingListInput = z.infer<typeof updateShoppingListSchema>;
export type ShoppingItemInput = z.infer<typeof shoppingItemSchema>;
export type UpdateShoppingItemInput = z.infer<typeof updateShoppingItemSchema>;
export type ShoppingListQueryInput = z.infer<typeof shoppingListQuerySchema>;

import { describe, it, expect } from "bun:test";
import type { z } from "zod";
import { updateHouseholdSchema } from "@/lib/validations/household";
import { updateStorageLocationSchema } from "@/lib/validations/inventory";
import { updateProductSchema } from "@/lib/validations/product";
import { updateShoppingListSchema } from "@/lib/validations/shopping";
import { updateStoreSchema } from "@/lib/validations/store";

/**
 * An edit changes the fields it sends and no other.
 *
 * Each of these is its create schema made `.partial()`, and each resolver
 * spreads the parsed input into `prisma.*.update`, where a key that is absent
 * leaves its column alone. Zod 3 left an omitted key absent even when the
 * create schema gave it a `.default()`. **Zod 4 fills the default in through
 * `.partial()` and `.optional()`**, so after the upgrade renaming a product
 * reset its unit to "unit", and renaming the auto-generated shopping list
 * turned it into an ordinary one. An update schema overrides every defaulted
 * field with a plain `.optional()`; this is what notices the next one that
 * does not.
 */

const UPDATE_SCHEMAS: [string, z.ZodType][] = [
  ["household", updateHouseholdSchema],
  ["storage location", updateStorageLocationSchema],
  ["product", updateProductSchema],
  ["shopping list", updateShoppingListSchema],
  ["store", updateStoreSchema],
];

describe("an edit fills in nothing it was not sent", () => {
  for (const [label, schema] of UPDATE_SCHEMAS) {
    it(`${label}: an id alone parses to an id alone`, () => {
      expect(schema.parse({ id: "c1" })).toEqual({ id: "c1" });
    });
  }

  it("still takes the defaulted fields when they are sent", () => {
    expect(updateProductSchema.parse({ id: "c1", defaultUnit: " kg " })).toEqual({ id: "c1", defaultUnit: "kg" });
    expect(updateShoppingListSchema.parse({ id: "c1", isAutoGenerated: true })).toEqual({
      id: "c1",
      isAutoGenerated: true,
    });
  });
});

import "../setup/matchers";
import { describe, it, expect, afterEach, beforeEach, mock } from "bun:test";
import { screen, cleanup } from "@testing-library/react";
import { TRPCClientError } from "@trpc/client";
import { createContext } from "react";
import { renderWithIntl } from "../utils/render";

/**
 * ISSUES.md UI-9, on the two routes that still had it.
 *
 * `/inventory` and `/products` were fixed with UI-8; `/shopping` and
 * `/settings/locations` kept testing `if (isLoading)` alone, so a failed query
 * fell straight through to the empty state. The result is a lie with a
 * plausible shape: someone with four lists is told they have none, and the
 * only tell is that creating one appears to do nothing.
 *
 * The assertion that matters is the *pair* — the failure copy is present AND
 * the empty-state copy is absent. Checking only the first would still pass if
 * a route rendered both, which is a different and equally wrong screen.
 *
 * This is the rendered tier because the question is which branch the component
 * takes, which is a fact about the DOM. Nothing here is geometric.
 */

interface QueryStub {
  data: unknown;
  isPending: boolean;
  error: unknown;
  fetchStatus: "fetching" | "paused" | "idle";
  refetch: () => void;
}

/** What both routes' queries return. Set per test before rendering. */
let queryStub: QueryStub;

const noop = (): void => {};
const idleMutation = { mutate: noop, isPending: false };

// `/shopping/lists` reports its writes through the snackbar, so the provider
// has to be here — `useSnackbar` throws outside it, deliberately, because
// feedback outside the shell is a bug. The real one rather than a stub:
// `mock.module` replaces a module process-wide and would reach
// `Snackbar.test.tsx`.
mock.module("@/components/offline/queue-context", () => ({
  WriteQueueContext: createContext(null),
  useWriteQueue: () => ({
    state: { pending: [], failed: [], status: "idle", full: false },
    enqueue: () => ({ ok: true, id: "op" }),
    drain: () => {},
    cancel: () => true,
    holdRemainingMs: () => 0,
    retry: () => {},
    discard: () => {},
    flush: async () => {},
    purgeAll: () => {},
  }),
}));

mock.module("@/lib/trpc/client", () => ({
  api: {
    useUtils: () => ({ invalidate: () => Promise.resolve() }),
    household: { create: { useMutation: () => idleMutation } },
    shopping: {
      list: { useQuery: () => queryStub },
      // The preview sits above the list and asks its own question. It is not
      // what is under test, so it stays quiet.
      getAutoList: { useQuery: () => ({ data: undefined, isLoading: false }) },
      create: { useMutation: () => idleMutation },
      generateFromLowStock: { useMutation: () => idleMutation },
    },
    location: { getTree: { useQuery: () => queryStub } },
  },
}));

const { SnackbarProvider } = await import("@/components/ui/snackbar");
const { default: ShoppingListsPage } = await import(
  "@/app/(dashboard)/shopping/lists/page"
);
const { default: LocationsPage } = await import(
  "@/app/(dashboard)/settings/locations/page"
);

/** A refusal shaped the way tRPC delivers one to the browser. */
function trpcError(code: string, httpStatus: number): TRPCClientError<never> {
  const error = new TRPCClientError<never>("refused");
  Object.defineProperty(error, "data", { value: { code, httpStatus } });
  return error;
}

const ROUTES = [
  {
    name: "/shopping/lists",
    Page: ShoppingListsPage,
    /** The lie this route told: "No hay listas de compra". */
    emptyState: /No hay listas de compra/,
    loaded: [
      { id: "list-1", name: "Compra del sábado", isAutoGenerated: false, items: [] },
    ],
    loadedText: "Compra del sábado",
  },
  {
    name: "/settings/locations",
    Page: LocationsPage,
    /** The lie this route told: "No hay ubicaciones configuradas." */
    emptyState: /No hay ubicaciones configuradas/,
    loaded: [
      {
        id: "loc-1",
        name: "Nevera",
        children: [],
        parentId: null,
        householdId: "h1",
      },
    ],
    loadedText: "Nevera",
  },
] as const;

beforeEach(() => {
  queryStub = {
    data: undefined,
    isPending: false,
    error: null,
    fetchStatus: "idle",
    refetch: noop,
  };
});

afterEach(cleanup);

describe("a route whose query failed", () => {
  for (const { name, Page, emptyState, loaded, loadedText } of ROUTES) {
    it(`${name} offers a retry instead of claiming the household is empty`, () => {
      queryStub = {
        data: undefined,
        isPending: false,
        error: trpcError("INTERNAL_SERVER_ERROR", 500),
        fetchStatus: "idle",
        refetch: noop,
      };

      renderWithIntl(
        <SnackbarProvider>
          <Page />
        </SnackbarProvider>,
      );

      expect(
        screen.getByText("No se han podido cargar los datos"),
      ).toBeInTheDocument();
      expect(screen.getByRole("button", { name: "Reintentar" })).toBeInTheDocument();
      expect(screen.queryByText(emptyState)).toBeAbsent();
    });

    it(`${name} offers a household form when that is what is missing`, () => {
      queryStub = {
        data: undefined,
        isPending: false,
        error: trpcError("PRECONDITION_FAILED", 412),
        fetchStatus: "idle",
        refetch: noop,
      };

      renderWithIntl(
        <SnackbarProvider>
          <Page />
        </SnackbarProvider>,
      );

      expect(
        screen.getByText("Todavía no tienes un hogar"),
      ).toBeInTheDocument();
      expect(screen.queryByText(emptyState)).toBeAbsent();
    });

    it(`${name} keeps showing what is loaded when a refetch cannot reach the server`, () => {
      // A background refetch that fails must not replace a working page with
      // a failure panel. The data is still true; only the refresh failed.
      queryStub = {
        data: loaded,
        isPending: false,
        error: trpcError("INTERNAL_SERVER_ERROR", 500),
        fetchStatus: "idle",
        refetch: noop,
      };

      renderWithIntl(
        <SnackbarProvider>
          <Page />
        </SnackbarProvider>,
      );

      expect(screen.getByText(loadedText)).toBeInTheDocument();
      expect(
        screen.queryByText("No se han podido cargar los datos"),
      ).toBeAbsent();
    });

    it(`${name} does not claim to be empty when there is no connection`, () => {
      // `fetchStatus: "paused"` is offline with nothing cached. It is not a
      // failure and it is not an empty household — it is "we have not asked".
      queryStub = {
        data: undefined,
        isPending: true,
        error: null,
        fetchStatus: "paused",
        refetch: noop,
      };

      renderWithIntl(
        <SnackbarProvider>
          <Page />
        </SnackbarProvider>,
      );

      expect(
        screen.getByText("Aquí todavía no hay nada guardado"),
      ).toBeInTheDocument();
      expect(screen.queryByText(emptyState)).toBeAbsent();
      expect(document.querySelector("[aria-busy]")).toBeAbsent();
    });

    it(`${name} still shows its empty state when the query succeeded with nothing`, () => {
      queryStub = {
        data: [],
        isPending: false,
        error: null,
        fetchStatus: "idle",
        refetch: noop,
      };

      renderWithIntl(
        <SnackbarProvider>
          <Page />
        </SnackbarProvider>,
      );

      expect(screen.getByText(emptyState)).toBeInTheDocument();
      expect(
        screen.queryByText("No se han podido cargar los datos"),
      ).toBeAbsent();
    });
  }
});

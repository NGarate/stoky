import "../setup/matchers";
import { describe, it, expect, afterEach, beforeEach, mock } from "bun:test";
import { screen, cleanup, fireEvent } from "@testing-library/react";
import { createContext } from "react";
import { renderWithIntl } from "../utils/render";
import { axeViolations } from "../utils/axe";

/**
 * Creating a list on /shopping/lists.
 *
 * The field was named only by its placeholder, so it lost its name the
 * moment anyone typed; pressing "Crear" on an empty field did nothing and
 * said nothing; and neither write said anything when the server refused it,
 * so a failure looked like a button that had not been pressed.
 */

type Options = {
  onSuccess?: (data: unknown) => void;
  onError?: (error: unknown) => void;
};

let createCalls: Array<Record<string, unknown>>;
let createOptions: Options = {};
let generateOptions: Options = {};

const noop = (): void => {};

mock.module("@/lib/offline/queue-context", () => ({
  WriteQueueContext: createContext(null),
  useWriteQueue: () => ({
    state: { pending: [], failed: [], status: "idle", full: false },
    enqueue: () => ({ ok: true, id: "op" }),
    drain: noop,
    cancel: () => true,
    holdRemainingMs: () => 0,
    retry: noop,
    discard: noop,
    flush: async () => 0,
    purgeAll: noop,
  }),
}));

mock.module("@/lib/trpc/client", () => ({
  api: {
    useUtils: () => ({
      invalidate: () => Promise.resolve(),
      shopping: {
        list: { invalidate: () => Promise.resolve() },
        getAutoList: { invalidate: () => Promise.resolve() },
      },
    }),
    household: {
      create: { useMutation: () => ({ mutate: noop, isPending: false }) },
    },
    shopping: {
      list: {
        useQuery: () => ({
          data: [
            { id: "l1", name: "Semanal", isAutoGenerated: false, items: [] },
          ],
          isPending: false,
          error: null,
          fetchStatus: "idle",
          refetch: noop,
        }),
      },
      getAutoList: { useQuery: () => ({ data: undefined, isLoading: false }) },
      create: {
        useMutation: (options: Options) => {
          createOptions = options;
          return {
            mutate: (input: Record<string, unknown>) => createCalls.push(input),
            isPending: false,
          };
        },
      },
      generateFromLowStock: {
        useMutation: (options: Options) => {
          generateOptions = options;
          return { mutate: noop, isPending: false };
        },
      },
    },
  },
}));

const { SnackbarProvider } = await import("@/components/ui/snackbar");
const { default: ShoppingListsPage } =
  await import("@/app/(dashboard)/shopping/lists/page");

function openForm(): void {
  renderWithIntl(
    <SnackbarProvider>
      <ShoppingListsPage />
    </SnackbarProvider>,
  );
  fireEvent.click(
    screen.getAllByRole("button", { name: "Crear lista" })[0] as HTMLElement,
  );
}

beforeEach(() => {
  createCalls = [];
  createOptions = {};
  generateOptions = {};
});

afterEach(cleanup);

describe("creating a list", () => {
  it("names its field with a label that stays when somebody types", () => {
    openForm();

    const field = screen.getByLabelText("Nombre de la lista");
    fireEvent.change(field, { target: { value: "Compra del sábado" } });

    expect(screen.getByLabelText("Nombre de la lista")).toBe(field);
  });

  it("says what to do when the name is empty, rather than doing nothing", () => {
    openForm();

    fireEvent.submit(
      screen
        .getByLabelText("Nombre de la lista")
        .closest("form") as HTMLFormElement,
    );

    expect(createCalls).toEqual([]);
    const field = screen.getByLabelText("Nombre de la lista");
    expect(field.getAttribute("aria-invalid")).toBe("true");
    expect(
      screen.getByText("Escribe un nombre para la lista."),
    ).toBeInTheDocument();
    expect(document.activeElement).toBe(field);
  });

  it("says a refused create failed, and keeps the name that was typed", async () => {
    openForm();

    const field = screen.getByLabelText("Nombre de la lista");
    fireEvent.change(field, { target: { value: "Compra del sábado" } });
    fireEvent.submit(field.closest("form") as HTMLFormElement);
    expect(createCalls).toEqual([{ name: "Compra del sábado" }]);

    createOptions.onError?.(new Error("refused"));

    expect(
      await screen.findByText(/No se ha podido crear la lista/),
    ).toBeInTheDocument();
    expect(
      (screen.getByLabelText("Nombre de la lista") as HTMLInputElement).value,
    ).toBe("Compra del sábado");
  });

  it("says a refused generate failed", async () => {
    renderWithIntl(
      <SnackbarProvider>
        <ShoppingListsPage />
      </SnackbarProvider>,
    );

    generateOptions.onError?.(new Error("refused"));

    expect(
      await screen.findByText(/No se ha podido generar la lista/),
    ).toBeInTheDocument();
  });
});

it("passes axe at AAA", async () => {
  const { container } = renderWithIntl(
    <SnackbarProvider>
      <ShoppingListsPage />
    </SnackbarProvider>,
  );
  await screen.findAllByText(/Semanal/);
  expect(await axeViolations(container)).toBe("");
});

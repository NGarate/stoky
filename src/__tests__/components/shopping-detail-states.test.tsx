import "../setup/matchers";
import { describe, it, expect, afterEach, beforeEach, mock } from "bun:test";
import { screen, cleanup } from "@testing-library/react";
import { TRPCClientError } from "@trpc/client";
import { createContext } from "react";
import { renderWithIntl } from "../utils/render";

/**
 * `/shopping/[id]` — the screen someone is actually holding in a shop.
 *
 * It read `if (isLoading)` and then `if (!list) return errors.notFound`. The
 * trap is that TanStack Query's `isLoading` is `isPending && isFetching`, and a
 * query paused for want of a connection is pending but **not** fetching. So
 * with no signal the guard was false, `list` was undefined, and the page said
 * the list does not exist — to someone standing in a supermarket looking at it.
 *
 * A genuinely deleted list must still say so, which is why the two cases are
 * told apart by the error code rather than by the absence of data.
 */

interface QueryStub {
  data: unknown;
  isPending: boolean;
  error: unknown;
  fetchStatus: "fetching" | "paused" | "idle";
  refetch: () => void;
}

let queryStub: QueryStub;

const noop = (): void => {};
const idleMutation = { mutate: noop, isPending: false };

mock.module("@/components/offline/queue-context", () => ({
  // A real context as well as the hook. `mock.module` replaces the module for
  // the whole process, and `WriteQueueProvider` renders
  // `WriteQueueContext.Provider` — so a mock that omits it turns the provider
  // into a syntax error in whichever suite renders the real one.
  WriteQueueContext: createContext(null),
  useWriteQueue: () => ({
    state: { pending: [], failed: [], status: "idle", full: false },
    enqueue: () => ({ ok: true as const, id: "op-1" }),
    drain: noop,
    retry: noop,
    discard: noop,
  }),
}));

mock.module("@/lib/trpc/client", () => ({
  api: {
    useUtils: () => ({
      invalidate: () => Promise.resolve(),
      shopping: {
        getById: { invalidate: noop },
        list: { invalidate: noop },
      },
    }),
    household: { create: { useMutation: () => idleMutation } },
    // The add form creates a product inline now, and the picker reads the
    // catalogue to offer one.
    product: {
      create: { useMutation: () => idleMutation },
      list: { useQuery: () => ({ data: { products: [] }, isLoading: false }) },
      getByBarcode: { useQuery: () => ({ data: null }) },
    },
    // The row offers a shop to buy at, and asks who is looking to decide
    // whether to render the controls at all.
    store: { list: { useQuery: () => ({ data: [], isLoading: false }) } },
    auth: { me: { useQuery: () => ({ data: { role: "OWNER" } }) } },
    shopping: {
      getById: { useQuery: () => queryStub },
      addItem: { useMutation: () => idleMutation },
      updateItem: { useMutation: () => idleMutation },
      removeItem: { useMutation: () => idleMutation },
      delete: { useMutation: () => idleMutation },
    },
  },
}));

const { ShoppingListView } = await import(
  "@/app/(dashboard)/shopping/[id]/page"
);

function trpcError(code: string, httpStatus: number): TRPCClientError<never> {
  const error = new TRPCClientError<never>("refused");
  Object.defineProperty(error, "data", { value: { code, httpStatus } });
  return error;
}

/**
 * The screen, not the route. The route's only job is `React.use(params)`, which
 * never resumes under this runtime — Suspense holds its fallback for ever — so
 * the screen takes a plain id and is rendered directly.
 */
function renderPage() {
  return renderWithIntl(<ShoppingListView id="list-1" />);
}

const LOADED = {
  id: "list-1",
  name: "Compra del sábado",
  isAutoGenerated: false,
  items: [
    {
      id: "item-1",
      productId: "p1",
      product: { name: "Leche entera" },
      quantity: 2,
      unit: "L",
      isChecked: false,
    },
  ],
};

beforeEach(() => {
  queryStub = {
    data: undefined,
    isPending: false,
    error: null,
    fetchStatus: "idle",
    refetch: noop,
  };
});

afterEach(cleanup);

describe("the shopping list someone is holding", () => {
  it("does not claim the list does not exist when there is no connection", () => {
    queryStub = {
      data: undefined,
      isPending: true,
      error: null,
      fetchStatus: "paused",
      refetch: noop,
    };

    renderPage();

    expect(
      screen.getByText("Aquí todavía no hay nada guardado"),
    ).toBeInTheDocument();
    expect(screen.queryByText("No encontrado")).toBeNull();
  });

  it("still says a deleted list is gone", () => {
    queryStub = {
      data: undefined,
      isPending: false,
      error: trpcError("NOT_FOUND", 404),
      fetchStatus: "idle",
      refetch: noop,
    };

    renderPage();

    expect(screen.getByText("No encontrado")).toBeInTheDocument();
    expect(screen.queryByText("Aquí todavía no hay nada guardado")).toBeNull();
  });

  it("offers a retry for any other failure", () => {
    queryStub = {
      data: undefined,
      isPending: false,
      error: trpcError("INTERNAL_SERVER_ERROR", 500),
      fetchStatus: "idle",
      refetch: noop,
    };

    renderPage();

    expect(
      screen.getByText("No se han podido cargar los datos"),
    ).toBeInTheDocument();
    expect(screen.queryByText("No encontrado")).toBeNull();
  });

  it("keeps showing the list when a refetch cannot reach the server", () => {
    queryStub = {
      data: LOADED,
      isPending: false,
      error: trpcError("INTERNAL_SERVER_ERROR", 500),
      fetchStatus: "idle",
      refetch: noop,
    };

    renderPage();

    // The list is still true. Only the refresh failed, and replacing a working
    // shopping list with a failure panel mid-shop is the worse answer.
    expect(screen.getByText("Leche entera")).toBeInTheDocument();
    expect(screen.queryByText("No se han podido cargar los datos")).toBeNull();
    expect(screen.queryByText("No encontrado")).toBeNull();
  });
});

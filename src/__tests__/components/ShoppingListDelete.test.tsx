import "../setup/matchers";
import { describe, it, expect, afterEach, beforeEach, mock } from "bun:test";
import { screen, cleanup, fireEvent } from "@testing-library/react";
import { createContext } from "react";
import { renderWithIntl } from "../utils/render";

/**
 * Deleting a shopping list.
 *
 * It used to leave by `window.location.href = "/shopping"`: a full reload
 * that threw away the client cache and the snackbar with it, so nothing said
 * the list had gone, and it landed on the shop screen rather than on the
 * lists the person came from. The button was a ghost — dressed like "Editar"
 * — and drawn for a KITCHEN account, whose `shopping.delete` the server
 * refuses (`writeProcedure`).
 */

type Options = { onSuccess?: () => void; onError?: () => void };

let role: string;
let deleteOptions: Options = {};
let deleteCalls: Array<Record<string, unknown>>;
let replaced: string[];
let shoppingInvalidated: number;
type Updater = (old: Array<Record<string, unknown>> | undefined) => unknown;
let buyListUpdaters: Updater[];
let listsUpdaters: Updater[];

const noop = (): void => {};
const idleMutation = { mutate: noop, isPending: false };

mock.module("next/navigation", () => ({
  useRouter: () => ({
    push: noop,
    replace: (href: string) => replaced.push(href),
    refresh: noop,
  }),
  useSearchParams: () => new URLSearchParams(),
  usePathname: () => "/shopping/list-1",
  useParams: () => ({ id: "list-1" }),
  redirect: noop,
}));

mock.module("@/lib/offline/queue-context", () => ({
  WriteQueueContext: createContext(null),
  useWriteQueue: () => ({
    state: { pending: [], failed: [], status: "idle", full: false },
    enqueue: () => ({ ok: true as const, id: "op-1" }),
    drain: noop,
    retry: noop,
    discard: noop,
    cancel: () => true,
    holdRemainingMs: () => 10_000,
  }),
}));

mock.module("@/lib/trpc/client", () => ({
  api: {
    useUtils: () => ({
      invalidate: () => Promise.resolve(),
      shopping: {
        invalidate: () => {
          shoppingInvalidated += 1;
          return Promise.resolve();
        },
        getById: { invalidate: noop },
        getBuyList: {
          setData: (_input: unknown, updater: Updater) => buyListUpdaters.push(updater),
        },
        list: {
          invalidate: () => Promise.resolve(),
          setQueriesData: (_input: unknown, _filters: unknown, updater: Updater) =>
            listsUpdaters.push(updater),
        },
      },
    }),
    household: { create: { useMutation: () => idleMutation } },
    product: {
      create: { useMutation: () => idleMutation },
      list: { useQuery: () => ({ data: { products: [] }, isLoading: false }) },
      getByBarcode: { useQuery: () => ({ data: null }) },
    },
    store: { list: { useQuery: () => ({ data: [], isLoading: false }) } },
    auth: { me: { useQuery: () => ({ data: { role } }) } },
    shopping: {
      getById: {
        useQuery: () => ({
          data: { id: "list-1", name: "Compra del sábado", isAutoGenerated: false, items: [] },
          isPending: false,
          error: null,
          fetchStatus: "idle",
          refetch: noop,
        }),
      },
      delete: {
        useMutation: (options: Options) => {
          deleteOptions = options;
          return {
            mutate: (input: Record<string, unknown>) => deleteCalls.push(input),
            isPending: false,
          };
        },
      },
    },
  },
}));

const { ShoppingListView } = await import("@/app/(dashboard)/shopping/[id]/page");
const { SnackbarProvider } = await import("@/components/ui/snackbar");

function renderPage(): void {
  renderWithIntl(
    <SnackbarProvider>
      <ShoppingListView id="list-1" />
    </SnackbarProvider>,
  );
}

beforeEach(() => {
  role = "MEMBER";
  deleteOptions = {};
  deleteCalls = [];
  replaced = [];
  shoppingInvalidated = 0;
  buyListUpdaters = [];
  listsUpdaters = [];
});

afterEach(cleanup);

describe("deleting a list", () => {
  it("is drawn as the destructive action it is", () => {
    renderPage();

    // The trigger is destructive-ghost (red words, no fill); the solid
    // destructive fill belongs to the confirming button in the dialog.
    const button = screen.getByRole("button", { name: "Eliminar lista" });
    expect(button.className).toContain("text-destructive");
  });

  it("is not offered to an account the server would refuse", () => {
    role = "KITCHEN";
    renderPage();

    expect(screen.queryByRole("button", { name: "Eliminar lista" })).toBeAbsent();
  });

  it("returns to the lists and says which one went, without a reload", async () => {
    renderPage();

    fireEvent.click(screen.getByRole("button", { name: "Eliminar lista" }));
    fireEvent.click(screen.getByRole("button", { name: "Sí, eliminar la lista" }));
    expect(deleteCalls).toEqual([{ id: "list-1" }]);

    deleteOptions.onSuccess?.();

    expect(replaced).toEqual(["/shopping/lists"]);
    expect(
      await screen.findByText("Eliminaste la lista «Compra del sábado»"),
    ).toBeInTheDocument();
  });

  it("leaves no cached read still holding the list it deleted", () => {
    // Only `shopping.list` was invalidated, so the buy list and this list's
    // own read — both persisted — still held the deleted list and its items.
    // /shopping showed them for the freshness window, and indefinitely
    // offline, where ticking one queued a write against a row that was gone.
    renderPage();

    deleteOptions.onSuccess?.();

    expect(shoppingInvalidated).toBe(1);
  });

  it("takes the list out of the copies an offline screen would restore", () => {
    // Marking them stale corrects a screen only when it mounts with signal.
    // Signal lost on the way to /shopping restored the deleted items, and
    // ticking one queued a write against a row that was gone.
    renderPage();

    deleteOptions.onSuccess?.();

    const buyList = [
      { id: "item-1", listId: "list-1" },
      { id: "item-2", listId: "list-2" },
    ];
    expect(buyListUpdaters.map((update) => update(buyList))).toEqual([
      [{ id: "item-2", listId: "list-2" }],
    ]);
    expect(listsUpdaters.map((update) => update([{ id: "list-1" }, { id: "list-2" }]))).toEqual([
      [{ id: "list-2" }],
    ]);
    // Nothing cached is not something to invent an empty list for.
    expect(buyListUpdaters[0]?.(undefined)).toBeUndefined();
  });

  it("says so when the server refuses", async () => {
    renderPage();

    deleteOptions.onError?.();

    expect(await screen.findByText(/No se ha podido eliminar la lista/)).toBeInTheDocument();
    expect(replaced).toEqual([]);
  });
});

"use client";

import { useTranslations } from "next-intl";
import Link from "next/link";
import { Button } from "@/components/ui/button";
import { api } from "@/lib/trpc/client";

export function AutoListPreview() {
  const t = useTranslations("shopping");
  const { data: autoList, isLoading } = api.shopping.getAutoList.useQuery();

  if (isLoading || !autoList || autoList.items.length === 0) {
    return null;
  }

  const uncheckedCount = autoList.items.filter((item) => !item.isChecked).length;

  if (uncheckedCount === 0) {
    return null;
  }

  // A panel, because it is a call to action — but on the card surface, not
  // `bg-warn`. A list the app drafted is not a warning, and the amber spent
  // the needs-attention tone on news that is merely useful.
  return (
    <div className="rounded-lg border border-border bg-card p-4">
      <div className="flex items-center justify-between">
        <div>
          <h2 className="font-semibold text-heading">{t("autoGenerated")}</h2>
          <p className="text-sm text-muted-foreground">
            {/* The string carries the number. Printed beside it as well, it
                read "3 3 artículos". */}
            {t("itemsCount", { count: uncheckedCount })}
          </p>
        </div>
        <Button asChild variant="default">
          <Link href={`/shopping/${autoList.id}`} > {t("view")} </Link>
        </Button>
      </div>
    </div>
  );
}

"use client";

import { useTranslations } from "next-intl";
import Link from "next/link";
import { Button } from "@/components/ui/button";
import { api } from "@/lib/trpc/client";

export function AutoListPreview() {
  const t = useTranslations("shopping");
  const { data: autoList, isLoading } = api.shopping.getAutoList.useQuery();

  if (isLoading || !autoList || autoList.items.length === 0) {
    return null;
  }

  const uncheckedCount = autoList.items.filter((item) => !item.isChecked).length;

  if (uncheckedCount === 0) {
    return null;
  }

  return (
    <div className="rounded-lg border border-warn-foreground bg-warn p-4">
      <div className="flex items-center justify-between">
        <div>
          <h2 className="font-semibold text-warn-foreground">{t("autoGenerated")}</h2>
          <p className="text-sm text-warn-foreground">
            {uncheckedCount} {t("itemsCount", { count: uncheckedCount })}
          </p>
        </div>
        <Button asChild variant="default">
          <Link href={`/shopping/${autoList.id}`} > {t("view")} </Link>
        </Button>
      </div>
    </div>
  );
}

"use client";

import { useTranslations } from "next-intl";
import Link from "next/link";
import { api } from "@/lib/trpc/client";

export function AutoListPreview() {
  const t = useTranslations("shopping");
  const { data: autoList, isLoading } = api.shopping.getAutoList.useQuery();

  if (isLoading || !autoList || autoList.items.length === 0) {
    return null;
  }

  const uncheckedCount = autoList.items.filter((item) => !item.isChecked).length;

  if (uncheckedCount === 0) {
    return null;
  }

  return (
    <div className="rounded-lg border border-yellow-200 bg-yellow-50 p-4">
      <div className="flex items-center justify-between">
        <div>
          <h3 className="font-semibold text-yellow-800">{t("autoGenerated")}</h3>
          <p className="text-sm text-yellow-600">
            {uncheckedCount} {t("itemsCount", { count: uncheckedCount })}
          </p>
        </div>
        <Link
          href={`/shopping/${autoList.id}`}
          className="rounded-md bg-yellow-600 px-4 py-2 text-sm font-medium text-white hover:bg-yellow-700"
        >
          {t("view")}
        </Link>
      </div>
    </div>
  );
}

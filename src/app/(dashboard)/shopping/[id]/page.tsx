"use client";

import React, { useState } from "react";
import { useTranslations } from "next-intl";
import Link from "next/link";
import { api } from "@/lib/trpc/client";
import { ShoppingItem } from "@/components/shopping/ShoppingItem";
import { RouteState, isNotFoundError } from "@/components/household/RouteState";

interface ShoppingListPageProps {
  params: Promise<{ id: string }>;
}

/**
 * The route, which exists only to unwrap its params.
 *
 * The screen is a separate component taking a plain `id`, because
 * `React.use(promise)` never resumes under the component tier's runtime —
 * Suspense holds its fallback for ever — and a screen that can only be
 * exercised by a browser is a screen whose states go unchecked. The split
 * costs one component and buys the four tests below it.
 */
export default function ShoppingListPage({ params }: ShoppingListPageProps) {
  const { id } = React.use(params);
  return <ShoppingListView id={id} />;
}

export function ShoppingListView({ id }: { id: string }) {
  const t = useTranslations();
  const [isAdding, setIsAdding] = useState(false);
  const [newItem, setNewItem] = useState({
    customName: "",
    quantity: 1,
    unit: "unit",
  });

  const listQuery = api.shopping.getById.useQuery({ id });
  const list = listQuery.data;

  const addItemMutation = api.shopping.addItem.useMutation({
    onSuccess: () => {
      setIsAdding(false);
      setNewItem({ customName: "", quantity: 1, unit: "unit" });
    },
  });

  const deleteListMutation = api.shopping.delete.useMutation({
    onSuccess: () => {
      window.location.href = "/shopping";
    },
  });

  const handleAddItem = (e: React.FormEvent) => {
    e.preventDefault();
    if (newItem.customName.trim()) {
      addItemMutation.mutate({
        shoppingListId: id,
        customName: newItem.customName.trim(),
        quantity: newItem.quantity,
        unit: newItem.unit,
      });
    }
  };

  // Data first. `isLoading` is `isPending && isFetching`, which is *false*
  // for a paused query — so with no signal this fell straight through to
  // "not found" and told someone standing in a shop that the list they were
  // shopping from does not exist (ISSUES.md UI-9).
  if (!list) {
    if (isNotFoundError(listQuery.error)) {
      return <div className="p-8">{t("errors.notFound")}</div>;
    }
    return (
      <RouteState
        error={listQuery.error}
        fetchStatus={listQuery.fetchStatus}
        isLoading={listQuery.isPending}
        onRetry={() => void listQuery.refetch()}
        title={t("shopping.title")}
      />
    );
  }

  const totalItems = list.items.length;
  const checkedItems = list.items.filter((item) => item.isChecked).length;
  const progress = totalItems > 0 ? (checkedItems / totalItems) * 100 : 0;

  return (
    <div className="space-y-6">
      <div className="flex items-center justify-between">
        <div className="flex items-center gap-4">
          <Link
            href="/shopping"
            className="rounded-md border border-input bg-card px-3 py-1 text-sm text-foreground hover:bg-accent hover:text-accent-foreground"
          >
            {t("common.back")}
          </Link>
          <div>
            <h1 className="text-2xl font-bold text-heading">{list.name}</h1>
            {list.isAutoGenerated && (
              <p className="text-sm text-warn-foreground">{t("shopping.autoDescription")}</p>
            )}
          </div>
        </div>
        <button
          type="button"
          onClick={() => {
            if (confirm(t("common.confirmDelete"))) {
              deleteListMutation.mutate({ id });
            }
          }}
          disabled={deleteListMutation.isPending}
          className="rounded-md px-4 py-2 text-sm text-destructive hover:bg-danger disabled:opacity-50"
        >
          {t("common.delete")}
        </button>
      </div>

      {totalItems > 0 && (
        <div className="rounded-lg border border-border bg-card p-4">
          <div className="mb-2 flex justify-between text-sm">
            <span>{t("shopping.progress")}</span>
            <span>
              {checkedItems}/{totalItems} {t("common.items")}
            </span>
          </div>
          <div className="h-2 rounded-full bg-gauge-track">
            <div
              className="h-2 rounded-full bg-gauge transition-all"
              style={{ width: `${progress}%` }}
            />
          </div>
        </div>
      )}

      <div className="flex items-center justify-between">
        <h2 className="text-lg font-semibold text-heading">{t("shopping.items")}</h2>
        {!isAdding && (
          <button
            type="button"
            onClick={() => setIsAdding(true)}
            className="rounded-md bg-primary px-4 py-2 text-sm text-primary-foreground hover:bg-primary/90"
          >
            {t("shopping.addItem")}
          </button>
        )}
      </div>

      {isAdding && (
        <form
          onSubmit={handleAddItem}
          className="rounded-lg border border-border bg-card p-4"
        >
          <div className="flex gap-2">
            <input
              type="text"
              placeholder={t("shopping.itemName")}
              value={newItem.customName}
              onChange={(e) =>
                setNewItem({ ...newItem, customName: e.target.value })
              }
              className="flex-1 rounded-md border border-input bg-card px-3 py-2 text-foreground"
            />
            <input
              type="number"
              min="0.1"
              step="0.1"
              value={newItem.quantity}
              onChange={(e) =>
                setNewItem({
                  ...newItem,
                  quantity: Number.parseFloat(e.target.value) || 1,
                })
              }
              className="w-20 rounded-md border border-input bg-card px-3 py-2 text-foreground"
            />
            <input
              type="text"
              placeholder={t("common.unit")}
              value={newItem.unit}
              onChange={(e) => setNewItem({ ...newItem, unit: e.target.value })}
              className="w-24 rounded-md border border-input bg-card px-3 py-2 text-foreground"
            />
            <button
              type="submit"
              disabled={addItemMutation.isPending}
              className="rounded-md bg-primary px-4 py-2 text-primary-foreground hover:bg-primary/90 disabled:opacity-50"
            >
              {t("common.add")}
            </button>
            <button
              type="button"
              onClick={() => {
                setIsAdding(false);
                setNewItem({ customName: "", quantity: 1, unit: "unit" });
              }}
              className="rounded-md border border-input bg-card px-4 py-2 text-foreground hover:bg-accent hover:text-accent-foreground"
            >
              {t("common.cancel")}
            </button>
          </div>
        </form>
      )}

      <div className="space-y-2">
        {list.items.length === 0 ? (
          <div className="rounded-lg border border-border bg-card p-8 text-center text-muted-foreground">
            <p>{t("shopping.emptyList")}</p>
            <p className="mt-2 text-sm">{t("shopping.addItems")}</p>
          </div>
        ) : (
          list.items.map((item) => (
            <ShoppingItem key={item.id} item={item} listId={id} />
          ))
        )}
      </div>
    </div>
  );
}

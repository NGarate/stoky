"use client";

import { useState } from "react";
import { useTranslations } from "next-intl";
import Link from "next/link";
import { api } from "@/lib/trpc/client";
import { AutoListPreview } from "@/components/shopping/AutoListPreview";

export default function ShoppingListsPage() {
  const t = useTranslations();
  const [isCreating, setIsCreating] = useState(false);
  const [newListName, setNewListName] = useState("");

  const { data: lists, isLoading } = api.shopping.list.useQuery({
    includeCompleted: false,
  });

  const createMutation = api.shopping.create.useMutation({
    onSuccess: () => {
      setIsCreating(false);
      setNewListName("");
    },
  });

  const generateMutation = api.shopping.generateFromLowStock.useMutation();

  const handleCreate = (e: React.FormEvent) => {
    e.preventDefault();
    if (newListName.trim()) {
      createMutation.mutate({ name: newListName.trim() });
    }
  };

  if (isLoading) {
    return <div className="p-8">{t("common.loading")}</div>;
  }

  return (
    <div className="space-y-6">
      <div className="flex items-center justify-between">
        <h1 className="text-2xl font-bold text-heading">{t("shopping.title")}</h1>
        <div className="flex gap-2">
          <button
            type="button"
            onClick={() => generateMutation.mutate()}
            disabled={generateMutation.isPending}
            className="rounded-md border border-input bg-card px-4 py-2 text-sm text-foreground hover:bg-accent hover:text-accent-foreground disabled:opacity-50"
          >
            {t("shopping.generateFromLowStock")}
          </button>
          <button
            type="button"
            onClick={() => setIsCreating(true)}
            className="rounded-md bg-primary px-4 py-2 text-sm text-primary-foreground hover:bg-primary/90"
          >
            {t("shopping.create")}
          </button>
        </div>
      </div>

      <AutoListPreview />

      {isCreating && (
        <form
          onSubmit={handleCreate}
          className="flex gap-2 rounded-lg border border-border bg-card p-4"
        >
          <input
            type="text"
            placeholder={t("shopping.listName")}
            value={newListName}
            onChange={(e) => setNewListName(e.target.value)}
            className="flex-1 rounded-md border border-input bg-card px-3 py-2 text-foreground"
          />
          <button
            type="submit"
            disabled={createMutation.isPending}
            className="rounded-md bg-primary px-4 py-2 text-primary-foreground hover:bg-primary/90 disabled:opacity-50"
          >
            {t("common.create")}
          </button>
          <button
            type="button"
            onClick={() => {
              setIsCreating(false);
              setNewListName("");
            }}
            className="rounded-md border border-input bg-card px-4 py-2 text-foreground hover:bg-accent hover:text-accent-foreground"
          >
            {t("common.cancel")}
          </button>
        </form>
      )}

      <div className="grid gap-4 md:grid-cols-2 lg:grid-cols-3">
        {lists?.length === 0 ? (
          <div className="col-span-full rounded-lg border border-border bg-card p-8 text-center text-muted-foreground">
            <p>{t("shopping.noLists")}</p>
            <p className="mt-2 text-sm">{t("shopping.createFirst")}</p>
          </div>
        ) : (
          lists?.map((list) => {
            const totalItems = list.items.length;
            const checkedItems = list.items.filter((item) => item.isChecked).length;
            const progress = totalItems > 0 ? (checkedItems / totalItems) * 100 : 0;

            return (
              <Link
                key={list.id}
                href={`/shopping/${list.id}`}
                className="rounded-lg border border-border bg-card p-4 shadow-sm transition-shadow hover:shadow-md"
              >
                <div className="mb-2 flex items-start justify-between">
                  <h3 className="font-semibold text-heading">{list.name}</h3>
                  {list.isAutoGenerated && (
                    <span className="rounded bg-warn px-2 py-0.5 text-xs text-warn-foreground">
                      {t("shopping.autoGenerated")}
                    </span>
                  )}
                </div>

                <p className="mb-3 text-sm text-muted-foreground">
                  {t("shopping.itemsCount", { count: totalItems })}
                </p>

                {totalItems > 0 && (
                  <div>
                    <div className="mb-1 flex justify-between text-xs">
                      <span>{t("shopping.progress")}</span>
                      <span>
                        {checkedItems}/{totalItems}
                      </span>
                    </div>
                    <div className="h-2 rounded-full bg-gauge-track">
                      <div
                        className="h-2 rounded-full bg-gauge transition-all"
                        style={{ width: `${progress}%` }}
                      />
                    </div>
                  </div>
                )}
              </Link>
            );
          })
        )}
      </div>
    </div>
  );
}
